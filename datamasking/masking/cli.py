def _apply_level1_settings_impl(args, config, logger) -> Optional[str]:
    system = getattr(config, 'system', None)
    rules = getattr(config, 'masking_rules', None)
    validation = getattr(config, 'validation', None)
    security = getattr(config, 'security', None)
    remask = getattr(config, 'remask', None)

    # system.version — файл для новішої мажорної версії програми
    cfg_version = getattr(system, 'version', '')
    cfg_major, prog_major = _major(cfg_version), _major(_cfg.__version__)
    if cfg_major is not None and prog_major is not None and cfg_major > prog_major:
        _config_warning(args, f"config is for version {cfg_version}, this program is "
                              f"{_cfg.__version__}; some options may not be understood")

    # Ключі з єдиним підтримуваним значенням
    checks = [
        (getattr(security, 'encryption_algorithm', None), "security.encryption_algorithm", ("AES-256-GCM",)),
        (getattr(getattr(security, 'password_generation', None), 'algorithm', None),
         "security.password_generation.algorithm", ("secrets",)),
        (getattr(remask, 'chain_format', None), "remask.chain_format", ("json",)),
    ]
    for value, name, allowed in checks:
        if value is not None and str(value).strip().lower() not in {a.lower() for a in allowed}:
            return f"{name}: only {', '.join(allowed)} is supported, got {value!r}"

    # Незмінна поведінка: приймається лише true
    from datamasking.extras.config import ALWAYS_ON_KEYS
    for dotted, reason in ALWAYS_ON_KEYS.items():
        section, key = dotted.split('.')
        value = getattr(getattr(config, section, None), key, True)
        if value is not True:
            return f"{dotted}: only true is supported, got {value!r} ({reason})"

    # masking_rules.preserve_case — перекриває system.preserve_case
    rules_case = getattr(rules, 'preserve_case', None)
    if rules_case is not None:
        _cfg.PRESERVE_CASE = bool(rules_case)

    # Ліміт розміру: діє менший із system.max_file_size_mb і validation.max_input_size_mb
    sys_mb = getattr(system, 'max_file_size_mb', None)
    if sys_mb is not None:
        limit_mb = _int_setting(sys_mb, "system.max_file_size_mb", 1, 1_000_000)
        _cfg.MAX_INPUT_FILE_SIZE = min(_cfg.MAX_INPUT_FILE_SIZE, limit_mb * 1024 * 1024)

    # Межі розпізнавання дат
    if validation is not None:
        if getattr(validation, 'validate_date_range', True) is False:
            _cfg.DATE_DETECT_YEAR_MIN, _cfg.DATE_DETECT_YEAR_MAX = 1, 9999
        else:
            lo = _int_setting(getattr(validation, 'min_date_year', 1900), "validation.min_date_year", 1, 9999)
            hi = _int_setting(getattr(validation, 'max_date_year', 2100), "validation.max_date_year", 1, 9999)
            if lo > hi:
                return f"validation.min_date_year ({lo}) is greater than validation.max_date_year ({hi})"
            _cfg.DATE_DETECT_YEAR_MIN, _cfg.DATE_DETECT_YEAR_MAX = lo, hi

    # Склеювання розірваних звань
    line_fix = getattr(rules, 'rank_line_break_fix', None)
    if line_fix is not None:
        _cfg.RANK_LINE_BREAK_FIX = bool(line_fix)

    # Текстові дати, прізвища, по батькові, номери документів: окремо або
    # «як відповідний загальний прапорець»
    if not getattr(args, 'only', None) and not getattr(args, 'exclude', None):
        def follow(key: str, base: bool) -> bool:
            value = getattr(rules, key, None)
            return base if value is None else bool(value)
        _cfg.MASK_DATE_TEXT = follow('enable_date_text', _cfg.MASK_DATES)
        _cfg.MASK_SURNAMES = follow('enable_surnames', _cfg.MASK_NAMES)
        _cfg.MASK_PATRONYMICS = follow('enable_patronymics', _cfg.MASK_NAMES)
        _cfg.MASK_DOCUMENT_NUMBERS = follow('enable_document_numbers', _cfg.MASK_ORDERS)

    # Перемаскування
    if remask is not None:
        if getattr(remask, 'enabled', True) is False and getattr(args, 're_mask', None):
            return "--re-mask is disabled by the configuration (remask.enabled: false)"
        _cfg.REMASK_MAX_PASSES = _int_setting(getattr(remask, 'max_passes', 10), "remask.max_passes", 2, 10)

    # Склад пароля — перевірити ДО запису файлів (сам пароль генерується пізніше)
    _password_policy(config)

    # Кодування вхідного файлу
    enc, allowed_list = check_encoding_settings(
        getattr(system, 'encoding', 'utf-8'),
        getattr(validation, 'allowed_encodings', None))
    _cfg.INPUT_ENCODING, _cfg.ALLOWED_ENCODINGS = enc, tuple(allowed_list)

    # Дайджест хешу (лише blake2b) і контрольна сума ІПН
    digest = getattr(system, 'hash_digest_size', None)
    if digest is not None:
        digest = _int_setting(digest, "system.hash_digest_size", 1, 64)
        if digest != 64 and str(_cfg.HASH_ALGORITHM).lower() != "blake2b":
            raise ValueError(f"system.hash_digest_size applies to blake2b only "
                             f"(hash_algorithm is {_cfg.HASH_ALGORITHM})")
        _cfg.HASH_DIGEST_SIZE = digest
    _cfg.VALIDATE_IPN_CHECKSUM = getattr(validation, 'validate_ipn_checksum', False) is True

    # Розпізнавання ПІБ
    min_len = getattr(validation, 'min_name_length', None)
    if min_len is not None:
        _cfg.NAME_MIN_LENGTH = _int_setting(min_len, "validation.min_name_length", 1, 100)
    max_len = getattr(validation, 'max_name_length', None)
    if max_len is not None:
        _cfg.NAME_MAX_LENGTH = _int_setting(max_len, "validation.max_name_length", 1, 1000)
        if _cfg.NAME_MAX_LENGTH < _cfg.NAME_MIN_LENGTH:
            raise ValueError(f"validation.max_name_length ({_cfg.NAME_MAX_LENGTH}) is less than "
                             f"min_name_length ({_cfg.NAME_MIN_LENGTH})")
    if getattr(validation, 'allow_abbreviated_patronymic', True) is False:
        _cfg.ALLOW_ABBREVIATED_PATRONYMIC = False
        print("Warning: validation.allow_abbreviated_patronymic is false — initials "
              "(\"Іванов І.І.\") are NOT masked; the surname only when it follows a rank",
              file=sys.stderr)
    if getattr(validation, 'strict_pib_format', False) is True:
        _cfg.STRICT_PIB_FORMAT = True
        print("Warning: validation.strict_pib_format is true — only full three-word names "
              "are masked; a surname alone or two words stay open", file=sys.stderr)

    # Рід масок імен (preserve_gender: false — не видавати стать)
    _cfg.PRESERVE_GENDER = getattr(rules, 'preserve_gender', True) is not False
    if not _cfg.PRESERVE_GENDER:
        print("Note: masking_rules.preserve_gender is false — first names and patronymics get a "
              "random gender; surname endings (-ова), feminine ranks and verbs can still reveal it",
              file=sys.stderr)

    # Власні шаблони і порядок фаз
    from datamasking.masking import custom as _custom
    router = getattr(config, 'router_rules', None)
    _cfg.CUSTOM_PATTERNS = _custom.compile_patterns(getattr(rules, 'custom_patterns', None),
                                                    getattr(router, 'default_action', 'mask'))

    # Виключення: вбудовані переліки + exclusions (фрази — як custom skip,
    # always_mask — як custom mask, після власних шаблонів)
    from datamasking.masking import exclusions as _exclusions
    excl = _exclusions.build(getattr(config, 'exclusions', None),
                             getattr(config, 'dictionaries', None))
    _cfg.ABBREVIATION_WHITELIST = excl.abbreviations
    _cfg.EXCLUDE_WORDS_LOWER = excl.words_lower
    _cfg.LEGAL_ACT_DATE_PREFIX = excl.legal_act_prefix
    _cfg.CUSTOM_PATTERNS = excl.skip_patterns + _cfg.CUSTOM_PATTERNS + excl.mask_patterns
    args._exclusions = excl
    _cfg.PROCESSING_ORDER = _custom.build_processing_order(
        getattr(router, 'processing_order', None), getattr(router, 'priority_overrides', None),
        _cfg.DEFAULT_PROCESSING_ORDER)

    # Виведення ключа для .enc (перевірка — до запису файлів)
    kdf = {
        "kdf": getattr(security, 'key_derivation', 'pbkdf2'),
        "n": getattr(security, 'scrypt_n', 16384),
        "r": getattr(security, 'scrypt_r', 8),
        "p": getattr(security, 'scrypt_p', 1),
        "salt_length": getattr(security, 'salt_length', 16),
    }
    if SECURITY_AVAILABLE:
        args._kdf = MappingSecurityManager.check_kdf(kdf)

    # Тимчасові файли
    temp_dir = str(getattr(system, 'temp_dir', '') or '')
    if temp_dir:
        if not Path(temp_dir).is_dir():
            raise ValueError(f"system.temp_dir {temp_dir!r} is not an existing directory")
        import tempfile
        tempfile.tempdir = temp_dir
    from datamasking import _fsutil
    _fsutil.SECURE_DELETE_TEMP = getattr(security, 'secure_delete_temp', True) is not False

    log_cfg = getattr(config, 'logging', None)
    _cfg.LOG_SENSITIVE_DATA = getattr(log_cfg, 'log_sensitive_data', False) is True
    _cfg.LOG_PERFORMANCE = getattr(log_cfg, 'log_performance', False) is True
    return None


def _apply_config_settings(args, config, logger) -> Optional[str]:
    """Apply config-based masking rules and system settings.

    Returns an error message (fatal for the CLI) or None.
    """
    if config is None:
        return None

    # Masking rules from config (only if --only/--exclude not specified)
    masking_rules = getattr(config, 'masking_rules', None)
    if masking_rules is not None:
        only_types = getattr(args, 'only', None) if SELECTIVE_AVAILABLE else None
        exclude_types = getattr(args, 'exclude', None) if SELECTIVE_AVAILABLE else None

        if not only_types and not exclude_types:
            config_rules_map = {
                'enable_ranks': 'MASK_RANKS',
                'enable_names': 'MASK_NAMES',
                'enable_ipn': 'MASK_IPN',
                'enable_passport': 'MASK_PASSPORT',
                'enable_military_id': 'MASK_MILITARY_ID',
                'enable_dates': 'MASK_DATES',
                'enable_brigades': 'MASK_BRIGADES',
                'enable_units': 'MASK_UNITS',
                'enable_orders': 'MASK_ORDERS',
                'enable_br_numbers': 'MASK_BR_NUMBERS',
            }
            for config_key, global_var in config_rules_map.items():
                value = getattr(masking_rules, config_key, None)
                if value is not None:
                    setattr(_cfg, global_var, bool(value))
                    if logger:
                        logger.debug(f"Config: {config_key} = {value}")

    # System settings from config
    system_cfg = getattr(config, 'system', None)
    if system_cfg is not None:
        cfg_debug = getattr(system_cfg, 'debug_mode', None)
        if cfg_debug is not None and not args.debug:
            _cfg.DEBUG_MODE = bool(cfg_debug)

        cfg_preserve_case = getattr(system_cfg, 'preserve_case', None)
        if cfg_preserve_case is not None:
            _cfg.PRESERVE_CASE = bool(cfg_preserve_case)

        cfg_hash = getattr(system_cfg, 'hash_algorithm', None)
        if cfg_hash is not None:
            _cfg.HASH_ALGORITHM = str(cfg_hash)

        # system.faker_locale — словники faker для синтетичних прізвищ/імен
        locale = getattr(system_cfg, 'faker_locale', None)
        if locale and locale != _cfg.FAKER_LOCALE:
            try:
                _cfg.set_faker_locale(str(locale))
            except ValueError as e:
                return str(e)
            if logger:
                logger.info(f"Faker locale: {locale}")

    # masking_rules.surname_prefix_length — скільки символів оригіналу лишати
    prefix_len = getattr(masking_rules, 'surname_prefix_length', None)
    if prefix_len is not None:
        try:
            prefix_len = int(prefix_len)
        except (TypeError, ValueError):
            return f"masking_rules.surname_prefix_length must be an integer, got {prefix_len!r}"
        if prefix_len < 0:
            return "masking_rules.surname_prefix_length must be >= 0"
        _cfg.SURNAME_PREFIX_LENGTH = prefix_len

    # validation.max_input_size_mb — раніше документований, але мертвий ключ
    validation_cfg = getattr(config, 'validation', None)
    max_mb = getattr(validation_cfg, 'max_input_size_mb', None)
    if isinstance(max_mb, int) and max_mb > 0:
        _cfg.MAX_INPUT_FILE_SIZE = max_mb * 1024 * 1024

    # security.encrypt_output — те саме, що --encrypt (раніше ігнорувався)
    security_cfg = getattr(config, 'security', None)
    if getattr(security_cfg, 'encrypt_output', False) and hasattr(args, 'encrypt') and not args.encrypt:
        args.encrypt = True
        if logger:
            logger.info("Encryption enabled by config (security.encrypt_output)")
    return _apply_level1_settings(args, config, logger)


def _prepare_output_paths(args, input_path: Path) -> Tuple[Path, Path, Path, str, int]:
    """Determine output, mapping, and report file paths.

    Mapping і звіт лягають ПОРУЧ із вихідним файлом (раніше — завжди у cwd,
    тож при `-o dir/x.txt` unmask не знаходив пару).
    """
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    is_json = input_path.suffix.lower() == '.json'
    ext = '.json' if is_json else '.txt'

    # Суфікс перекидаємо, поки набір імен не унікальний: два запуски в одну
    # секунду раніше могли мовчки перезаписати файли одне одного (p≈1/900)
    for _ in range(50):
        random_suffix = random.randint(100, 999)
        output_path = Path(args.output) if args.output else Path(f"output_{timestamp}_{random_suffix}{ext}")
        out_dir = output_path.parent
        map_path = out_dir / f"masking_map_{timestamp}_{random_suffix}.json"
        report_path = out_dir / f"masking_report_{timestamp}_{random_suffix}.txt"
        clashes = [map_path, map_path.with_suffix('.enc'), report_path]
        if not args.output:
            clashes.append(output_path)
        if not any(p.exists() for p in clashes):
            break

    return output_path, map_path, report_path, timestamp, random_suffix


def _validate_output_paths(args, input_path: Path, output_path: Path) -> Optional[str]:
    """Захист від втрати даних: -o не може вказувати на вхід і не
    перезаписує існуючий файл без --force. Повертає текст помилки або None."""
    try:
        same = output_path.resolve() == input_path.resolve()
    except OSError:
        same = False
    if same:
        return f"Output file must differ from input file: {output_path}"
    if output_path.exists() and not getattr(args, 'force', False):
        return f"Output file already exists: {output_path} (use --force to overwrite)"
    return None


def _resolve_password(args, config, logger) -> Tuple[Optional[str], Optional[str]]:
    """Визначає пароль для --encrypt ДО запису будь-яких файлів.

    Пріоритет: --password → --password-env VAR → $DATA_MASKING_PASSWORD →
    згенерований (показується один раз у stderr).
    Явно вказана, але порожня/відсутня змінна — помилка, а не мовчазна
    підміна випадковим паролем.

    Returns:
        (password, None) або (None, error_message)
    """
    password = getattr(args, 'password', None)
    if password is not None:
        if not password:
            return None, "--password must not be empty"
        return password, None

    password_env = getattr(args, 'password_env', None)
    if password_env:
        password = os.environ.get(password_env)
        if not password:
            return None, f"Environment variable '{password_env}' is not set or empty"
        return password, None

    env_name, generation_allowed, _length = _password_settings(config)
    password = os.environ.get(env_name)
    if password:
        if logger:
            logger.info(f"Password taken from ${env_name}")
        return password, None

    if not generation_allowed:
        return None, (f"--encrypt needs a password: set ${env_name}, use --password-env VAR, "
                      f"or allow generation (security.auto_generate_password)")

    password_file = str(getattr(getattr(config, 'security', None), 'password_file', '') or '')
    if password_file:
        target = Path(password_file)
        if target.exists() and not getattr(args, 'force', False):
            return None, f"security.password_file {target} already exists (use --force to overwrite)"
        args._password_file = target

    password = generate_password_from_config(config)
    _print_generated_password(password, getattr(args, '_password_file', None))
    return password, None


def _read_input(input_path: Path, is_json: bool, logger, masking_dict: Optional[Dict] = None):
    """Read input file (JSON or text) in system.encoding (or detected: auto).

    Використане кодування запам'ятовується в masking_dict["input_encoding"]
    (якщо не utf-8): вихід пишеться ним же, а unmask читає й пише ним же.
    """
    try:
        validate_file_size(input_path, _cfg.MAX_INPUT_FILE_SIZE)
        text, used = read_text(input_path, _cfg.INPUT_ENCODING, _cfg.ALLOWED_ENCODINGS)
        if used != "utf-8":
            print(f"Input encoding: {used}" + (" (auto)" if _cfg.INPUT_ENCODING == "auto" else ""))
            if masking_dict is not None:
                masking_dict["input_encoding"] = used
        if logger:
            logger.info(f"Input encoding: {used}")
        return json.loads(text) if is_json else text
    except (FileNotFoundError, PermissionError, OSError, json.JSONDecodeError,
            UnicodeDecodeError, ValueError) as e:
        print(f"Error reading file: {e}")
        if logger:
            logger.error(f"Error reading file: {e}")
        return None


def _run_masking(input_data, is_json: bool, masking_dict: Dict,
                 instance_counters: Dict, args, logger,
                 timestamp: str, random_suffix: int) -> Tuple[Any, int, Optional[Any]]:
    """Execute single-pass or multi-pass masking.

    Returns:
        (masked_data, total_unique, chain) — chain є лише у multi-pass
        режимі; його збереження (і шифрування) робить _save_results.
    """
    re_mask_passes = getattr(args, 're_mask', None)

    if re_mask_passes is not None:
        if re_mask_passes < 2:
            print("Warning: --re-mask requires at least 2 passes, using single-pass mode")
            if logger:
                logger.warning("--re-mask value < 2, falling back to single-pass")
            re_mask_passes = None
        elif re_mask_passes > _cfg.REMASK_MAX_PASSES:
            cap = _cfg.REMASK_MAX_PASSES
            print(f"Warning: --re-mask capped at {cap} passes (was {re_mask_passes})")
            if logger:
                logger.warning(f"--re-mask capped at {cap} (requested {re_mask_passes})")
            re_mask_passes = cap

    if REMASK_AVAILABLE and re_mask_passes and re_mask_passes > 1:
        return _run_multi_pass_masking(
            input_data, is_json, masking_dict, args, logger,
            re_mask_passes, timestamp, random_suffix
        )
    else:
        masked_data, total_unique = _run_single_pass_masking(
            input_data, is_json, masking_dict, instance_counters, logger
        )
        return masked_data, total_unique, None


def _run_multi_pass_masking(input_data, is_json: bool, masking_dict: Dict,
                            args, logger, re_mask_passes: int,
                            timestamp: str, random_suffix: int) -> Tuple[Any, int, Any]:
    """Execute multi-pass re-masking with chain tracking.

    Chain НЕ зберігається тут — _save_results запише його (plaintext або
    .enc при --encrypt) поруч із вихідним файлом.
    """
    if logger:
        logger.info(f"Starting multi-pass re-masking ({re_mask_passes} passes)")

    chain = MappingChain()
    masked_data = input_data

    for pass_num in range(1, re_mask_passes + 1):
        print(f"  Прохід {pass_num}/{re_mask_passes}...")
        if logger:
            logger.info(f"Re-masking pass {pass_num}/{re_mask_passes}")

        pass_dict = make_empty_masking_dict(_cfg.__version__)
        pass_counters: Dict[str, int] = {}

        if is_json:
            masked_data = mask_json_recursive(masked_data, pass_dict, pass_counters)
        else:
            masked_data = mask_text_context_aware(masked_data, pass_dict, pass_counters)

        pass_dict["instance_tracking"] = pass_counters
        for category, mappings in pass_dict["mappings"].items():
            pass_dict["statistics"][category] = len(mappings)
        chain.add_pass(pass_dict)

    masking_dict["instance_tracking"] = {}
    total_unique = 0
    for p in chain.passes:
        for cat, count in p.get("statistics", {}).items():
            masking_dict["statistics"][cat] = masking_dict["statistics"].get(cat, 0) + count
            if cat != "total_masked":
                total_unique += count
    masking_dict["statistics"]["total_masked"] = total_unique

    return masked_data, total_unique, chain


def _run_single_pass_masking(input_data, is_json: bool, masking_dict: Dict,
                             instance_counters: Dict, logger) -> Tuple[Any, int]:
    """Execute single-pass masking."""
    if logger:
        logger.info("Starting single-pass masking")

    if is_json:
        masked_data = mask_json_recursive(input_data, masking_dict, instance_counters)
    else:
        masked_data = mask_text_context_aware(input_data, masking_dict, instance_counters)

    masking_dict["instance_tracking"] = instance_counters

    total_unique = 0
    for category, mappings in masking_dict["mappings"].items():
        count = len(mappings)
        masking_dict["statistics"][category] = count
        total_unique += count
    masking_dict["statistics"]["total_masked"] = total_unique

    return masked_data, total_unique


def _print_generated_password(password: str, saved_to: Optional[Path] = None) -> None:
    """Показує згенерований пароль у stderr (не stdout), щоб він не
    потрапляв у перенаправлений вивід, пайпи та логи CI."""
    import sys
    if saved_to:
        print(f"  Generated password (also saved to {saved_to}, mode 0600):", file=sys.stderr)
    else:
        print("  Generated password (shown once, NOT saved anywhere):", file=sys.stderr)
    print(f"  {password}", file=sys.stderr)


def _write_mapping(mapping: Dict, json_path: Path, password: Optional[str],
                   logger, kdf: Optional[Dict] = None) -> Path:
    """Записує mapping (звичайний або chain) — ОДИН файл.

    Без пароля: plaintext JSON (атомарно, 0600).
    З паролем: лише .enc — plaintext на диск не потрапляє взагалі
    (раніше --encrypt писав .json І .enc поруч).
    """
    if password:
        enc_path = json_path.with_suffix('.enc')
        MappingSecurityManager().encrypt_mapping(mapping, password, enc_path, kdf=kdf)
        if logger:
            logger.info(f"Mapping encrypted to {enc_path}")
        return enc_path

    payload = json.dumps(mapping, ensure_ascii=False, indent=2).encode("utf-8")
    atomic_write_private(json_path, payload)
    return json_path


