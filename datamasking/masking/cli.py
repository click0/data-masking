def _load_config(args) -> Tuple[Optional[Any], Optional[str]]:
    """Load configuration: YAML (якщо є) + ENV-перекриття.

    Раніше без config.yaml loader узагалі не запускався, і всі
    DATA_MASKING_* змінні мовчки ігнорувались; битий YAML давав дефолти
    з написом «Loaded config». Тепер: loader працює завжди (ENV діє без
    файлу), помилка читання/розбору явно вказаного або наявного файлу —
    фатальна для CLI.

    Returns:
        (config, None) або (None, error_message)
    """
    if not CONFIG_AVAILABLE:
        return None, None

    config_path = args.config
    if config_path is not None and not Path(config_path).exists():
        return None, f"Config file not found: {config_path}"

    try:
        loader = ConfigLoader(config_path, local_path=getattr(args, 'config_local', None),
                              use_local=not getattr(args, 'no_local_config', False))
        config = loader.load()
    except (FileNotFoundError, PermissionError, ValueError, OSError) as e:
        return None, f"Could not load config: {e}"

    source = loader.loaded_from
    if source:
        print(f"Loaded config from {source}")
    for local in loader.local_loaded:
        print(f"Loaded local config from {local}")
    for notice in loader.notices:
        print(notice, file=sys.stderr)
    for ignored_source, keys in loader.ignored_by_source:
        warning = format_ignored_keys_warning(ignored_source, keys)
        if is_strict(config):
            return None, "strict_mode: " + warning.replace("Warning: ", "", 1)
        print(warning, file=sys.stderr)
    if loader.local_loaded:
        source = ", ".join(([source] if source else []) + loader.local_loaded)
    try:
        setattr(config, "_source", source)  # для звіту; dataclass дозволяє атрибут
    except AttributeError:
        pass
    return config, None


def _setup_logger(args, config) -> Optional[Any]:
    """Set up structured logging."""
    if not LOGGING_AVAILABLE:
        return None

    log_level = args.log_level
    log_file = args.log_file
    log_cfg = getattr(config, 'logging', None) if config is not None else None
    cli_logging = log_level is not None or log_file is not None

    # logging.enabled: false — структурований лог вимкнено (прапорці CLI
    # --log-level / --log-file все одно вмикають його на цей запуск)
    if getattr(log_cfg, 'enabled', True) is False and not cli_logging:
        return None

    if log_cfg is not None:
        if log_level is None:
            log_level = getattr(log_cfg, 'level', None)
        if log_file is None:
            to_file = getattr(log_cfg, 'log_to_file', None)
            cfg_file = getattr(log_cfg, 'file', None)
            if to_file is not False:
                log_file = cfg_file
            if to_file is True and not cfg_file:
                _config_warning(args, "logging.log_to_file is true but logging.file is not set — "
                                      "logging to the console only")

    if log_level is None:
        log_level = "INFO"
    console = getattr(log_cfg, 'log_to_console', True) is not False

    # logging.format (рядок у файлі логу), max_log_size_mb + log_rotation_count
    file_format = getattr(log_cfg, 'format', None) or None
    if file_format:
        import logging as _std_logging
        try:
            _std_logging.Formatter(file_format, validate=True)
        except (ValueError, TypeError) as e:
            _config_warning(args, f"logging.format is invalid ({e}) — using the default format")
            file_format = None
    max_bytes, backup_count = 0, 5
    size_mb = getattr(log_cfg, 'max_log_size_mb', None)
    if size_mb is not None:
        try:
            max_bytes = _int_setting(size_mb, "logging.max_log_size_mb", 1, 100_000) * 1024 * 1024
            backup_count = _int_setting(getattr(log_cfg, 'log_rotation_count', 5),
                                        "logging.log_rotation_count", 0, 1000)
        except ValueError as e:
            _config_warning(args, f"{e} — log rotation disabled")
            max_bytes = 0

    try:
        logger = setup_logging(level=log_level, log_file=log_file, console=console,
                               file_format=file_format, max_bytes=max_bytes,
                               backup_count=backup_count)
        logger.info(f"Data Masking Script v{_cfg.__version__} started")
        return logger
    except (ValueError, OSError, TypeError) as e:
        print(f"Warning: could not setup logging: {e}")
        return None


def _apply_selective_filters(args, logger) -> Optional[str]:
    """Apply --only / --exclude selective masking filters.

    Розбір імен типів делеговано extras.selective (канонічні імена,
    множина, українські форми, групи, кома/пробіл як роздільник) — раніше
    CLI мав власну несумісну таблицю, і невідомий тип тихо давав
    «замасковано нічого» з exit 0.

    Returns:
        None — ок; рядок з помилкою — невідомий тип (виклик має завершити
        роботу з EXIT_USAGE, НЕ записавши жодного файлу).
    """
    if not SELECTIVE_AVAILABLE:
        return None

    only_types = getattr(args, 'only', None)
    exclude_types = getattr(args, 'exclude', None)

    if not only_types and not exclude_types:
        return None

    if only_types and exclude_types:
        return "--only and --exclude cannot be combined"

    only_str = " ".join(only_types) if only_types else None
    exclude_str = " ".join(exclude_types) if exclude_types else None
    try:
        selective_filter = create_filter(only=only_str, exclude=exclude_str)
    except ValueError as e:
        if logger:
            logger.error(f"Selective masking: {e}")
        return str(e)

    if not selective_filter.enabled_types:
        return "Selective masking would disable every type — nothing to do"

    apply_filter_to_globals(selective_filter, vars(_cfg))

    mode = "--only" if only_types else "--exclude"
    source = getattr(args, '_selective_source', None)
    if source:
        mode = f"{source} ({mode})"
    enabled = ", ".join(selective_filter.get_enabled_list())
    print(f"Selective masking: {mode} {only_str or exclude_str} → enabled: {enabled}")
    if logger:
        logger.info(f"Selective masking: {mode} {only_str or exclude_str} → enabled: {enabled}")
    return None


def _config_warning(args, message: str) -> None:
    """Попередження конфігурації; у суворому режимі — помилка (main
    завершує роботу з кодом 1 до запису файлів)."""
    if getattr(args, '_strict', False):
        args._strict_errors = getattr(args, '_strict_errors', []) + [message]
    else:
        print(f"Warning: {message}", file=sys.stderr)


def _selective_from_config(args, config) -> Optional[str]:
    """router_rules.only_types / skip_types → як --only / --exclude.

    Діє, лише якщо в CLI немає ні --only, ні --exclude (CLI пріоритетніший).
    Як і в CLI, разом не поєднуються. Повертає помилку або None.
    """
    router = getattr(config, 'router_rules', None) if config is not None else None
    if router is None or getattr(args, 'only', None) or getattr(args, 'exclude', None):
        return None

    def as_list(name: str) -> Tuple[Optional[List[str]], Optional[str]]:
        value = getattr(router, name, None)
        if value in (None, "", []):
            return None, None
        if isinstance(value, str):
            value = [value]
        if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
            return None, f"router_rules.{name} must be a list of type names, got {value!r}"
        return list(value), None

    only, err = as_list('only_types')
    if err:
        return err
    skip, err = as_list('skip_types')
    if err:
        return err
    if only and skip:
        return "router_rules.only_types and router_rules.skip_types cannot be combined"
    if only:
        args.only, args._selective_source = only, "router_rules.only_types"
    elif skip:
        args.exclude, args._selective_source = skip, "router_rules.skip_types"
    return None


def _major(version: str) -> Optional[int]:
    m = re.match(r"^\s*v?(\d+)", str(version or ""))
    return int(m.group(1)) if m else None


def _int_setting(value, name: str, lo: int, hi: int) -> int:
    """Ціле в межах [lo, hi]; інакше ValueError з текстом для користувача."""
    if isinstance(value, bool):
        raise ValueError(f"{name} must be an integer, got {value!r}")
    try:
        n = int(value)
    except (TypeError, ValueError):
        raise ValueError(f"{name} must be an integer, got {value!r}") from None
    if not lo <= n <= hi:
        raise ValueError(f"{name} must be between {lo} and {hi}, got {n}")
    return n


